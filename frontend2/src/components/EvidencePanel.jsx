import { BookOpen, CircleAlert, FileSearch, Quote, TriangleAlert } from 'lucide-react';
import ClauseTags from './ClauseTags';
import ConfidenceLabel from './ConfidenceLabel';
import VerificationLabel from './VerificationLabel';

export default function EvidencePanel({ clause, tags, panelRef }) {
  if (!clause) {
    return (
      <section ref={panelRef} className="card evidence-panel evidence-panel--empty" aria-label="Evidence">
        <FileSearch size={28} aria-hidden="true" />
        <p>Select a clause to inspect its supporting passage.</p>
      </section>
    );
  }

  return (
    <section ref={panelRef} className="card evidence-panel" aria-labelledby="evidence-heading" tabIndex={-1}>
      <p className="eyebrow">Evidence</p>
      <h2 id="evidence-heading" className="evidence-panel__title">{clause.title}</h2>
      <div className="evidence-panel__meta">
        <span className="page-ref">{clause.page ? `Page ${clause.page}` : 'Page not provided'}</span>
        <VerificationLabel verified={clause.evidence_verified} />
        <ConfidenceLabel level={clause.confidence} />
        <ClauseTags tags={tags} />
      </div>

      <h3 className="section-label">
        <Quote size={14} aria-hidden="true" /> Source passage
      </h3>
      {clause.source_quote ? (
        <blockquote className={`source-quote ${clause.evidence_verified ? '' : 'source-quote--unverified'}`}>
          {clause.source_quote}
        </blockquote>
      ) : (
        <p className="muted">No supporting passage was returned for this finding.</p>
      )}
      {!clause.evidence_verified && (
        <div className="alert alert--warning alert--compact" role="note">
          <TriangleAlert size={18} aria-hidden="true" className="alert__icon" />
          <p>
            <strong>Unverified quotation.</strong> The backend has not confirmed that this text appears in your
            document. Check the original{clause.page ? ` on page ${clause.page}` : ''} before relying on this finding.
          </p>
        </div>
      )}

      <div className="finding finding--explicit">
        <h3 className="finding__label">
          <BookOpen size={15} aria-hidden="true" /> What the document states
        </h3>
        <p>{clause.explicit_meaning || <span className="muted">No plain-language restatement provided.</span>}</p>
      </div>

      <div className="finding finding--interpretation">
        <h3 className="finding__label">
          <CircleAlert size={15} aria-hidden="true" /> Possible concern (interpretation)
        </h3>
        <p>{clause.potential_concern || <span className="muted">No concern was flagged for this clause.</span>}</p>
        <p className="muted small">
          This is a possible reading generated by the model, not a statement found in the document.
        </p>
      </div>

      <p className="muted small evidence-panel__footnote">
        Model-reported confidence is a rough indicator, not a calibrated probability. Tags marked by keyword match are a
        reading aid only.
      </p>
    </section>
  );
}
